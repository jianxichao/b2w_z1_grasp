#!/usr/bin/env python3
"""Install apt-resolved ROS binaries under .runtime without sudo or system changes.

Packages come from this computer's configured apt repositories; dpkg-deb extracts
payloads only. No maintainer scripts or services are executed.
"""
import concurrent.futures
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT/'.runtime'
REQUESTED = ['ros-humble-navigation2','ros-humble-nav2-bringup',
             'ros-humble-rmw-cyclonedds-cpp','ros-humble-pointcloud-to-laserscan',
             'ros-humble-slam-toolbox']


def main():
    RUNTIME.mkdir(exist_ok=True)
    cache = RUNTIME/'debs'
    cache.mkdir(exist_ok=True)
    env = dict(os.environ, LC_ALL='C')
    result = subprocess.run(['apt-get','-s','--no-install-recommends','install',*REQUESTED],
                            env=env, text=True, capture_output=True, check=True)
    (RUNTIME/'apt-plan.txt').write_text(result.stdout)
    packages = [m.groups() for m in re.finditer(r'^Inst (\S+)(?: \[[^\]]+\])? \((\S+)', result.stdout, re.M)
                if not m.group(1).endswith(':i386')]
    if not packages:
        print('All requested runtime dependencies are already installed system-wide.')
        return
    print(f'Downloading {len(packages)} apt-resolved packages into {cache}', flush=True)

    def download(item):
        name, version = item
        log = cache/(name.replace(':','_')+'.log')
        proc = subprocess.run(['apt-get','download',name+'='+version], cwd=cache,
                              env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        log.write_text(proc.stdout)
        if proc.returncode:
            raise RuntimeError(f'Cannot download {name}: {proc.stdout[-1200:]}')
        return name

    with concurrent.futures.ThreadPoolExecutor(max_workers=5) as executor:
        for done, future in enumerate(concurrent.futures.as_completed([executor.submit(download,p) for p in packages]),1):
            name = future.result()
            if done%10==0 or done==len(packages):
                print(f'Downloaded {done}/{len(packages)} ({name})',flush=True)
    prefix = RUNTIME/'root'
    prefix.mkdir(exist_ok=True)
    for deb in sorted(cache.glob('*.deb')):
        subprocess.run(['dpkg-deb','-x',str(deb),str(prefix)],check=True)
    (RUNTIME/'manifest.json').write_text(json.dumps({'requested':REQUESTED,'resolved':packages,
        'installation':'extracted Debian package payloads; no system installation or maintainer scripts'},indent=2)+'\n')
    (RUNTIME/'env.bash').write_text('''# Generated by scripts/install_runtime.py. Scope: this shell and its children.
B2W_RUNTIME_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/root" && pwd)"
B2W_RUNTIME_ROS="$B2W_RUNTIME_ROOT/opt/ros/humble"
export AMENT_PREFIX_PATH="$B2W_RUNTIME_ROS:${AMENT_PREFIX_PATH:-}"
export CMAKE_PREFIX_PATH="$B2W_RUNTIME_ROS:${CMAKE_PREFIX_PATH:-}"
export PATH="$B2W_RUNTIME_ROS/bin:${PATH}"
export PYTHONPATH="$B2W_RUNTIME_ROS/local/lib/python3.10/dist-packages:$B2W_RUNTIME_ROS/lib/python3.10/site-packages:${PYTHONPATH:-}"
export LD_LIBRARY_PATH="$B2W_RUNTIME_ROS/lib:$B2W_RUNTIME_ROS/lib/x86_64-linux-gnu:$B2W_RUNTIME_ROOT/usr/lib/x86_64-linux-gnu:$B2W_RUNTIME_ROOT/usr/lib:$B2W_RUNTIME_ROOT/lib/x86_64-linux-gnu:${LD_LIBRARY_PATH:-}"
''')
    ros_prefix = prefix/'opt/ros/humble'
    (ros_prefix/'local_setup.bash').write_text('source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)/env.bash"\n')
    print('Runtime installed. Run: source setup.bash',flush=True)


if __name__=='__main__':
    main()
