"""Map TargetPoseResult JSON to task-manager string events.

Event interface:
- topic: /task_event
- type: std_msgs/msg/String
- format: event_name:detail

The mapping functions are ROS-independent and can be tested on Windows.
ROS imports are intentionally delayed until an actual publish is requested.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any, Mapping, Sequence


POSE_FAILURE_STATUSES = frozenset(
    {
        "laser_distance_unavailable",
        "too_few_laser_points",
        "scan_no_return",
        "invalid_bbox",
        "image_size_mismatch",
        "frame_id_mismatch",
    }
)

IGNORED_STATUSES = frozenset(
    {
        "low_confidence",
        "ignored_class",
    }
)


def result_to_task_event(result: Mapping[str, Any]) -> str | None:
    """Convert one TargetPoseResult-like mapping to a task event string.

    Returns None for results that should not trigger a task-manager event.
    A colon is always included in emitted events, even when detail is empty.
    """

    status = str(result.get("status", "")).strip()
    in_grasp_range = bool(result.get("in_grasp_range", False))

    if status == "ok":
        if in_grasp_range:
            return "target_in_grasp_range:"
        return "target_pose_ready:"

    if status in POSE_FAILURE_STATUSES:
        return f"pose_failed:{status}"

    if status in IGNORED_STATUSES or not status:
        return None

    # Unknown statuses are deliberately ignored instead of inventing an
    # unsupported state-machine event.
    return None


def load_results(path: str | Path) -> list[dict[str, Any]]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, list):
        raise ValueError("TargetPoseResult JSON must be a list.")

    results: list[dict[str, Any]] = []
    for index, item in enumerate(payload):
        if not isinstance(item, dict):
            raise ValueError(
                f"TargetPoseResult item {index} must be a JSON object."
            )
        results.append(item)
    return results


def build_events(results: Sequence[Mapping[str, Any]]) -> list[str]:
    events: list[str] = []
    for result in results:
        event = result_to_task_event(result)
        if event is not None:
            events.append(event)
    return events


def publish_events(
    events: Sequence[str],
    topic: str = "/task_event",
    discovery_wait_sec: float = 1.0,
) -> None:
    """Publish task events through ROS2.

    ROS packages are imported lazily so --dry-run remains usable without ROS2.
    """

    try:
        import rclpy
        from rclpy.node import Node
        from std_msgs.msg import String
    except ImportError as exc:
        raise RuntimeError(
            "ROS2 Python packages are unavailable. "
            "Run this command in a sourced ROS2 environment, "
            "or use --dry-run on Windows."
        ) from exc

    rclpy.init()
    node = Node("pose_task_event_publisher")
    publisher = node.create_publisher(String, topic, 10)

    try:
        deadline = time.monotonic() + max(0.0, discovery_wait_sec)
        while time.monotonic() < deadline:
            rclpy.spin_once(node, timeout_sec=0.05)

        for event in events:
            message = String()
            message.data = event
            publisher.publish(message)
            node.get_logger().info(f"published task event: {event}")
            rclpy.spin_once(node, timeout_sec=0.1)
    finally:
        node.destroy_node()
        rclpy.shutdown()


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Publish task events derived from TargetPoseResult JSON."
    )
    parser.add_argument(
        "--result-json",
        required=True,
        help="TargetPoseResult JSON generated by target_pose_estimator.",
    )
    parser.add_argument(
        "--topic",
        default="/task_event",
        help="Task event topic. Default: /task_event",
    )
    parser.add_argument(
        "--discovery-wait-sec",
        type=float,
        default=1.0,
        help="DDS discovery wait before publishing. Default: 1.0",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print events without importing ROS2 or publishing.",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()

    try:
        results = load_results(args.result_json)
        events = build_events(results)
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 2

    if not events:
        print("[SKIP] no task event generated")
        return 0

    if args.dry_run:
        for event in events:
            print(event)
        return 0

    try:
        publish_events(
            events,
            topic=args.topic,
            discovery_wait_sec=args.discovery_wait_sec,
        )
    except RuntimeError as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 2

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
